"""Generates the ghost logo of the About credits page from the PCB silkscreen
footprint hardware/libs/ghost_logo.kicad_mod (read only): the circuit ghost
whose traces, vias and chips are cut out of the body. One A8 mask, recoloured
by the screen. Writes src/components/ui/fonts/ui_img_logo.c and
include/ui_logo.h.

Run by gen_fonts.sh with the ESP-IDF Python (needs Pillow):
    python -I tools/gen_logo.py
"""
import os
import re

from PIL import Image, ImageChops, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "hardware", "libs", "ghost_logo.kicad_mod")
OUT_C = os.path.join(HERE, "..", "src", "components", "ui", "fonts", "ui_img_logo.c")
OUT_H = os.path.join(HERE, "..", "src", "components", "ui", "include", "ui_logo.h")

HEIGHT = 124
SS = 4


def polygons(text):
    blocks = re.findall(r"\(fp_poly\s*\(pts(.*?)\)\s*\(stroke", text, re.S)
    return [[(float(x), float(y)) for x, y in re.findall(r"\(xy ([-\d.]+) ([-\d.]+)\)", b)] for b in blocks]


def render():
    with open(SRC) as f:
        polys = polygons(f.read())
    xs = [p[0] for q in polys for p in q]
    ys = [p[1] for q in polys for p in q]
    min_x, min_y = min(xs), min(ys)
    scale = (HEIGHT * SS - 1) / (max(ys) - min_y)
    w = int((max(xs) - min_x) * scale) + 1
    h = HEIGHT * SS
    mask = Image.new("1", (w, h), 0)
    # Holes are separate polygons in the footprint, so the fill is even-odd.
    for q in polys:
        layer = Image.new("1", (w, h), 0)
        ImageDraw.Draw(layer).polygon([((x - min_x) * scale, (y - min_y) * scale) for x, y in q], fill=1)
        mask = ImageChops.logical_xor(mask, layer)
    return mask.convert("L").resize((-(-w // SS), HEIGHT), Image.LANCZOS)


def main():
    img = render()
    data = img.tobytes()
    rows = [", ".join(f"0x{b:02X}" for b in data[y * img.width:(y + 1) * img.width]) for y in range(img.height)]
    with open(OUT_C, "w") as f:
        f.write("/* Generated by firmware/tools/gen_logo.py. Do not edit. */\n#include \"lvgl.h\"\n\n")
        f.write("static const uint8_t ui_img_logo_map[] = {\n    " + ",\n    ".join(rows) + "\n};\n\n")
        f.write("const lv_image_dsc_t ui_img_logo = {\n"
                f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {img.width}, "
                f".h = {img.height}, .stride = {img.width}}},\n"
                "    .data_size = sizeof(ui_img_logo_map),\n    .data = ui_img_logo_map,\n};\n")
    with open(OUT_H, "w") as f:
        f.write("/* Generated by firmware/tools/gen_logo.py. Do not edit. */\n#pragma once\n\n#include \"lvgl.h\"\n\n"
                "/* The PCB silkscreen ghost as an A8 mask (the traces are holes). */\n"
                "LV_IMAGE_DECLARE(ui_img_logo);\n\n"
                f"#define UI_LOGO_W  {img.width}\n#define UI_LOGO_H  {img.height}\n")
    print(f"logo {img.width}x{img.height}, {len(data)} bytes")


if __name__ == "__main__":
    main()
