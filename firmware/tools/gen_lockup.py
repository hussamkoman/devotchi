"""Generates the lock-up (design-system 1): the wordmark `devotchi` in Figtree
Bold whose i wears Devo's antenna (cream stem, mango tip) instead of a dot,
after `wordmark()` in docs/design/tools/build.py. Two A8 masks, recoloured by
the screen: the cream word with the stem, and the tip. Writes
src/components/ui/fonts/ui_img_lockup.c and include/ui_lockup.h.

Run by gen_fonts.sh with the ESP-IDF Python (needs Pillow):
    python -I tools/gen_lockup.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, "..", "..", "docs", "design", "fonts", "Figtree-Bold.ttf")
OUT_C = os.path.join(HERE, "..", "src", "components", "ui", "fonts", "ui_img_lockup.c")
OUT_H = os.path.join(HERE, "..", "src", "components", "ui", "include", "ui_lockup.h")

SIZE = 30
SS = 4
# Antenna in the 20x22 box of build.py, placed at (-1.4, -8.5) from the top left of the dotless i.
STEM = ((5.4, 21), (5.4, 10), (12.5, 6.5))
STEM_W = 3.2
TIP = (14, 5.4, 4.6)
BOX = (-1.4, -8.5)


def bezier(p0, p1, p2, n=48):
    return [((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
             (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]) for t in (i / n for i in range(n + 1))]


def render():
    font = ImageFont.truetype(FONT, SIZE * SS)
    stem_text = "devotch"
    top = 10 * SS
    w = int(font.getlength(stem_text + "ı")) + 8 * SS
    h = 36 * SS + top
    word = Image.new("L", (w, h), 0)
    tip = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(word)
    # The CSS line box is 36 px for a 30 px font: the glyphs sit 3 px below its top.
    d.text((0, top + 3 * SS), stem_text, font=font, fill=255, anchor="la")
    ix = font.getlength(stem_text)
    d.text((ix, top + 3 * SS), "ı", font=font, fill=255, anchor="la")
    ox, oy = ix + BOX[0] * SS, top + BOX[1] * SS
    pts = [(ox + x * SS, oy + y * SS) for x, y in bezier(*STEM)]
    d.line(pts, fill=255, width=round(STEM_W * SS), joint="curve")
    r = STEM_W * SS / 2
    for x, y in (pts[0], pts[-1]):
        d.ellipse((x - r, y - r, x + r, y + r), fill=255)
    cx, cy, cr = ox + TIP[0] * SS, oy + TIP[1] * SS, TIP[2] * SS
    ImageDraw.Draw(tip).ellipse((cx - cr, cy - cr, cx + cr, cy + cr), fill=255)
    word = word.resize((w // SS, h // SS), Image.LANCZOS)
    tip = tip.resize((w // SS, h // SS), Image.LANCZOS)
    box = word.getbbox()
    tbox = tip.getbbox()
    full = (min(box[0], tbox[0]), min(box[1], tbox[1]), max(box[2], tbox[2]), max(box[3], tbox[3]))
    return word.crop(full), tip.crop(tbox), (tbox[0] - full[0], tbox[1] - full[1])


def c_array(name, img):
    data = img.tobytes()
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + img.width]) for i in range(0, len(data), img.width)]
    body = ",\n    ".join(rows)
    return (f"static const uint8_t {name}_map[] = {{\n    {body}\n}};\n\n"
            f"const lv_image_dsc_t {name} = {{\n"
            f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {img.width}, "
            f".h = {img.height}, .stride = {img.width}}},\n"
            f"    .data_size = sizeof({name}_map),\n    .data = {name}_map,\n}};\n")


def main():
    word, tip, (tx, ty) = render()
    with open(OUT_C, "w") as f:
        f.write("/* Generated by firmware/tools/gen_lockup.py. Do not edit. */\n#include \"lvgl.h\"\n\n")
        f.write(c_array("ui_img_lockup", word) + "\n" + c_array("ui_img_lockup_tip", tip))
    with open(OUT_H, "w") as f:
        f.write("/* Generated by firmware/tools/gen_lockup.py. Do not edit. */\n#pragma once\n\n#include \"lvgl.h\"\n\n"
                "/* The lock-up as two A8 masks: the word with the antenna stem (cream) and the tip (mango). */\n"
                "LV_IMAGE_DECLARE(ui_img_lockup);\nLV_IMAGE_DECLARE(ui_img_lockup_tip);\n\n"
                f"#define UI_LOCKUP_W      {word.width}\n#define UI_LOCKUP_H      {word.height}\n"
                f"/** Top left of the tip inside the word image. */\n#define UI_LOCKUP_TIP_X  {tx}\n#define UI_LOCKUP_TIP_Y  {ty}\n")
    print(f"lock-up {word.width}x{word.height}, tip {tip.width}x{tip.height} at {tx},{ty}")


if __name__ == "__main__":
    main()
