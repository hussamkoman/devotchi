"""Generates the icon font (design-system 7) for LVGL from the ICON paths in
docs/design/tools/build.py: one A4 glyph per icon at private-use code points
from U+E000, plus the 16 px hold glyphs (the button glyph at 60 % in a ring).
Writes src/components/ui/fonts/ui_font_icons.c and include/ui_icons.h.

Run by gen_fonts.sh with the ESP-IDF Python; needs ImageMagick (`magick`,
with its SVG renderer) for the rasterisation.
    python -I tools/gen_icons.py
"""
import ast
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD_PY = os.path.join(HERE, "..", "..", "docs", "design", "tools", "build.py")
OUT = os.path.join(HERE, "..", "src", "components", "ui", "fonts")

NAMES = [
    "check", "x", "dot", "chev", "up", "down", "terminal", "pencil", "globe", "plug", "warn", "shield", "q",
    "speech", "list", "menu", "stop", "bell", "bolt", "desk", "sun", "moon", "clock", "buzz", "wifi", "pet",
    "play", "info", "box0", "box1", "reset",
]
HOLDS = ["x", "dot", "check"]
FIRST = 0xE000


def icon_paths():
    tree = ast.parse(open(BUILD_PY, encoding="utf-8").read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "ICON" for t in node.targets):
            return ast.literal_eval(node.value)
    sys.exit("ICON not found in build.py")


def svg_icon(inner):
    # White on black, read back as grey: a dark stroke inside a filled shape (box1) knocks out.
    inner = inner.replace('stroke="#F3EEE3"', 'stroke="#000"')
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="14" height="14" viewBox="0 0 14 14" fill="none" '
            'stroke="#fff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" color="#fff">'
            f'<rect width="14" height="14" fill="#000" stroke="none"/>{inner}</svg>')


def svg_hold(inner):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" fill="none" '
            'stroke="#fff" stroke-linecap="round" stroke-linejoin="round" color="#fff">'
            '<rect width="16" height="16" fill="#000" stroke="none"/>'
            '<circle cx="8" cy="8" r="7" stroke-width="1.5"/>'
            f'<g transform="translate(3.8 3.8) scale(.6)" stroke-width="2.6">{inner}</g></svg>')


def raster(svg, size):
    out = subprocess.run(["magick", "-background", "black", "-density", "96", "svg:-", "-colorspace", "gray",
                          "-depth", "8", f"gray:-"], input=svg.encode(), capture_output=True, check=True).stdout
    if len(out) != size * size:
        sys.exit(f"unexpected raster size {len(out)}")
    return out


def pack_a4(px, w, h):
    """Crops to the ink box and packs 4 bpp, two pixels per byte, high nibble first."""
    rows = [i for i in range(h) if any(px[i * w + x] for x in range(w))]
    cols = [x for x in range(w) if any(px[i * w + x] for i in range(h))]
    if not rows:
        return b"", 0, 0, 0, 0
    y0, y1, x0, x1 = rows[0], rows[-1], cols[0], cols[-1]
    bw, bh = x1 - x0 + 1, y1 - y0 + 1
    nib = [px[(y0 + i) * w + x0 + x] >> 4 for i in range(bh) for x in range(bw)]
    if len(nib) % 2:
        nib.append(0)
    data = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    return data, bw, bh, x0, y0


def main():
    icons = icon_paths()
    glyphs = []
    for name in NAMES:
        glyphs.append((name, 14, raster(svg_icon(icons[name]), 14)))
    for name in HOLDS:
        glyphs.append(("hold_" + name, 16, raster(svg_hold(icons[name]), 16)))

    line_h, base = 16, 1
    bitmap, dsc, defs = [], [], []
    for i, (name, size, px) in enumerate(glyphs):
        data, bw, bh, x0, y0 = pack_a4(px, size, size)
        # The 14 px icons sit centred on the 16 px line; ofs_y is measured from the baseline up.
        top = y0 + (line_h - size) // 2
        ofs_y = (line_h - base) - top - bh
        dsc.append(f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {size * 16}, .box_w = {bw}, .box_h = {bh}, "
                   f".ofs_x = {x0}, .ofs_y = {ofs_y}}}, /* {name} */")
        bitmap.extend(data)
        cp = FIRST + i
        utf8 = chr(cp).encode("utf-8")
        defs.append(f'#define UI_ICON_{name.upper():<12} "' + "".join(f"\\x{b:02X}" for b in utf8) + '"')

    rows = [", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) for i in range(0, len(bitmap), 16)]
    c = f"""/* Generated by firmware/tools/gen_icons.py from the ICON paths in docs/design/tools/build.py. Do not edit. */
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
    {(","+chr(10)+"    ").join(rows)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
    {{.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}},
{chr(10).join(dsc)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = 0x{FIRST:X}, .range_length = {len(glyphs)}, .glyph_id_start = 1, .unicode_list = NULL,
     .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t ui_font_icons = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line_h},
    .base_line = {base},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0,
    .underline_thickness = 0,
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
"""
    h = ("/* Generated by firmware/tools/gen_icons.py. Do not edit. */\n#pragma once\n\n"
         "/* UTF-8 strings of the glyphs in ui_font_icons (design-system 7); hold_* are 16 px, the rest 14 px. */\n"
         + "\n".join(defs) + "\n")
    with open(os.path.join(OUT, "ui_font_icons.c"), "w") as f:
        f.write(c)
    with open(os.path.join(OUT, "..", "include", "ui_icons.h"), "w") as f:
        f.write(h)
    print(f"ui_font_icons: {len(glyphs)} glyphs, {len(bitmap)} bitmap bytes")


if __name__ == "__main__":
    main()
